export class Raster {
  readonly rgb: Uint8Array;
  constructor(
    readonly width: number,
    readonly height: number,
  ) {
    this.rgb = new Uint8Array(width * height * 3);
    this.fill(0, 0, width, height, [15, 23, 34]);
  }

  pixel(x: number, y: number, color: Color) {
    if (x < 0 || y < 0 || x >= this.width || y >= this.height) return;
    const at = (Math.floor(y) * this.width + Math.floor(x)) * 3;
    this.rgb[at] = color[0];
    this.rgb[at + 1] = color[1];
    this.rgb[at + 2] = color[2];
  }

  fill(x: number, y: number, width: number, height: number, color: Color) {
    for (let dy = 0; dy < height; dy++)
      for (let dx = 0; dx < width; dx++) this.pixel(x + dx, y + dy, color);
  }

  text(text: string, x: number, y: number, color: Color = [239, 245, 250]) {
    const normalized = text
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toUpperCase();
    for (const char of normalized) {
      const glyph = glyphs[char] ?? glyphs["?"];
      for (let bit = 0; bit < 35; bit++)
        if (glyph[bit] === "1")
          this.pixel(x + (bit % 5), y + Math.floor(bit / 5), color);
      x += 6;
    }
  }
}
